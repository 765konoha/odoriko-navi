-- =========================================================
-- 予定の完了判定を「運営の操作」か「時刻の経過」かで切り替える
--
-- 予定が当日に動くのは高知くらいで、それ以外の祭りでは完了操作が
-- 手間になっていた。祭りごとに自動完了を選べるようにする。
--
-- 完了状態そのものは保存しない(is_completed は運営の操作だけで立つ)。
-- 自動完了は「終了時刻、無ければ開始時刻を過ぎたか」をアプリ側で判定する。
-- 絶対時刻(timestamptz)同士の比較なので、時差の影響は受けない。
--
-- 演舞回数の集計(dance_count_enabled)を使う祭りでは、完了時に回数を
-- 記録する必要があるため、この設定に関わらず手動完了のみとする。
-- =========================================================

alter table festivals
  add column schedule_auto_complete boolean not null default false;

comment on column festivals.schedule_auto_complete is
  '予定の完了を時刻の経過で自動判定するか。false=運営の完了操作のみ。演舞回数の集計中は無効。';
